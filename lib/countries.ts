export const countries: Country[] = countryData.map(([code, name, currency]) => ({ code, name, currency }));
const countriesByCode = new Map(countries.map((country) => [country.code, country]));

export function getCountry(code?: string) {
  return code ? countriesByCode.get(code.trim().toUpperCase()) : undefined;
}

const searchable = (value: string) => value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();

export function searchCountries(query: string) {
  const term = searchable(query.trim());
  const exactCountry = getCountry(term);
  if (exactCountry) return [exactCountry];
  return countries.filter((country) => searchable(`${country.name} ${country.code} ${country.currency}`).includes(term));
}

export function defaultCurrency(settings: Pick<AppSettings, "countryCode" | "budgetCurrency">) {
  return getCountry(settings.countryCode)?.currency ?? settings.budgetCurrency ?? "USD";
}

export function countrySettingsPatch(settings: AppSettings, code: string): Partial<AppSettings> {
  const country = getCountry(code);
  if (!country) throw new Error("Choose a supported country.");
  return {
    countryCode: country.code,
    // Never relabel an existing budget as a different currency without conversion.
    ...(settings.monthlyBudget > 0 ? {} : { budgetCurrency: country.currency }),
  };
}
